// Reads the project records from the Cloud database and writes them into
// src/data/projects.generated.ts so the site can be built fully static.
// Run before `vite build`. Idempotent: same data in, same file out.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUTPUT = path.join(ROOT, "src/data/projects.generated.ts");

/** Minimal .env reader: the build runs this with plain node, not Vite. */
function loadEnv() {
  const file = path.join(ROOT, ".env");
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (!match) continue;
    const [, key, rawValue] = match;
    if (process.env[key] === undefined) {
      process.env[key] = rawValue.replace(/^["']|["']$/g, "");
    }
  }
}

const COLUMNS =
  "slug,name,domain,summary,description,tech,url,icon,started,detail_path,credits,sites";

async function fetchProjects() {
  const url = process.env["SUPABASE_URL"] ?? process.env["VITE_SUPABASE_URL"];
  const key =
    process.env["SUPABASE_PUBLISHABLE_KEY"] ?? process.env["VITE_SUPABASE_PUBLISHABLE_KEY"];
  if (!url || !key) throw new Error("Missing SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY");

  const endpoint = `${url}/rest/v1/projects?select=${COLUMNS}&order=started.desc`;
  const response = await fetch(endpoint, { headers: { apikey: key } });
  if (!response.ok) {
    throw new Error(`Project read failed: ${response.status} ${await response.text()}`);
  }
  const rows = await response.json();
  if (!Array.isArray(rows) || rows.length === 0) throw new Error("No project rows returned");
  return rows;
}

function render(rows) {
  const normalized = rows.map((row) => ({
    slug: row.slug,
    name: row.name,
    domain: row.domain,
    summary: row.summary,
    description: row.description,
    tech: row.tech ?? [],
    url: row.url,
    icon: row.icon,
    started: row.started,
    detail_path: row.detail_path ?? null,
    credits: Array.isArray(row.credits) ? row.credits : [],
    sites: Array.isArray(row.sites) ? row.sites : [],
  }));

  return `/**
 * Generated by scripts/generate-projects.mjs from the Cloud database.
 * Do not edit by hand: it is rewritten on every build.
 */
import type { GeneratedProjectRow } from "./projects.generated-types";

export const generatedProjectRows: readonly GeneratedProjectRow[] = ${JSON.stringify(
    normalized,
    null,
    2,
  )} as const;
`;
}

loadEnv();

const hasCredentials = Boolean(
  (process.env["SUPABASE_URL"] ?? process.env["VITE_SUPABASE_URL"]) &&
    (process.env["SUPABASE_PUBLISHABLE_KEY"] ?? process.env["VITE_SUPABASE_PUBLISHABLE_KEY"]),
);

// Without database credentials (e.g. a static host's CI), keep the committed
// generated file: it holds the data as of the last credentialed build.
if (!hasCredentials) {
  if (!fs.existsSync(OUTPUT)) {
    throw new Error("No database credentials and no committed projects.generated.ts to reuse");
  }
  console.log("No database credentials; keeping existing src/data/projects.generated.ts");
  process.exit(0);
}

let rows;
try {
  rows = await fetchProjects();
} catch (err) {
  // The database may be unreachable (wrong credentials, deleted project,
  // offline CI). Fall back to the committed generated file instead of
  // failing the whole build.
  if (fs.existsSync(OUTPUT)) {
    console.warn(
      `Project fetch failed (${err.message}); keeping existing src/data/projects.generated.ts`,
    );
    process.exit(0);
  }
  throw err;
}
const contents = render(rows);
const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
if (current !== contents) fs.writeFileSync(OUTPUT, contents);
console.log(`Wrote ${rows.length} projects to src/data/projects.generated.ts`);
